def _sqlite_prepare_runtime_database():
    global DB_PATH, _initialized
    if _initialized and os.path.isfile(DB_PATH):
        return
    if _IS_VERCEL:
        DB_PATH = _RUNTIME_TMP
    else:
        try:
            os.makedirs(os.path.dirname(SOURCE_DB_PATH), exist_ok=True)
            test_path = SOURCE_DB_PATH + ".write-test"
            with open(test_path, "ab"):
                pass
            os.remove(test_path)
            DB_PATH = SOURCE_DB_PATH
        except (OSError, PermissionError):
            DB_PATH = _RUNTIME_TMP
    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
    if not os.path.exists(DB_PATH):
        if os.path.isfile(SOURCE_DB_PATH) and os.access(SOURCE_DB_PATH, os.R_OK) and DB_PATH != SOURCE_DB_PATH:
            shutil.copyfile(SOURCE_DB_PATH, DB_PATH)
        elif DB_PATH != SOURCE_DB_PATH:
            from database.init_db import create_tables
            conn = sqlite3.connect(DB_PATH)
            try:
                create_tables(conn)
                conn.commit()
            finally:
                conn.close()
    conn = sqlite3.connect(DB_PATH, timeout=15)
    conn.close()
    _initialized = True


def _qmark_to_pyformat(sql):
    """Convert the project's SQLite ? placeholders to psycopg2 %s."""
    return sql.replace("?", "%s")


def _sqlite_datetime_to_postgres(sql):
    return re.sub(r"datetime\('now'\)", "CURRENT_TIMESTAMP", sql, flags=re.IGNORECASE)


class _PGCursor:
    def __init__(self, cursor):
        self._cursor = cursor
        self.lastrowid = None

    def execute(self, sql, params=None):
        self._cursor.execute(sql, params or ())
        if self._cursor.description and self._cursor.description[0].name == "id":
            try:
                row = self._cursor.fetchone()
                if row and isinstance(row, dict):
                    self.lastrowid = row.get("id")
                if row is not None:
                    # Re-execute is not desirable; this path is only used for
                    # INSERT ... RETURNING generated below by _PGConnection.
                    self._prefetched = row
                else:
                    self._prefetched = None
            except Exception:
                self._prefetched = None
        return self

    def fetchone(self):
        if hasattr(self, "_prefetched"):
            row = self._prefetched
            del self._prefetched
            return row
        return self._cursor.fetchone()

    def fetchall(self):
        rows = []
        if hasattr(self, "_prefetched"):
            rows.append(self._prefetched)
            del self._prefetched
        rows.extend(self._cursor.fetchall())
        return rows

    def __getattr__(self, name):
        return getattr(self._cursor, name)


class _PGConnection:
    def __init__(self, raw):
        self._raw = raw

    def execute(self, sql, params=None):
        sql = _sqlite_datetime_to_postgres(_qmark_to_pyformat(sql))
        stripped = sql.lstrip().upper()
        # The application reads cursor.lastrowid after these inserts. PostgreSQL
        # has no lastrowid, so return the generated id transparently.
        if stripped.startswith("INSERT INTO") and "RETURNING" not in stripped:
            table_match = re.match(r"INSERT\s+INTO\s+([A-Za-z_][A-Za-z0-9_]*)", sql, re.I)
            if table_match and table_match.group(1).lower() in {"users", "tasks", "incidents", "simulations"}:
                sql = sql.rstrip().rstrip(";") + " RETURNING id"
        cur = self._raw.cursor()
        wrapped = _PGCursor(cur)
        wrapped.execute(sql, params)
        return wrapped

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        self._raw.close()


def _ensure_postgres_schema():
    global _pg_initialized
    if _pg_initialized:
        return
    import psycopg2
    from psycopg2.extras import RealDictCursor
    raw = psycopg2.connect(SUPABASE_DB_URL, sslmode="require", connect_timeout=10, cursor_factory=RealDictCursor)
    try:
        raw.autocommit = True
        with raw.cursor() as cur:
            cur.execute(POSTGRES_SCHEMA)
    finally:
        raw.close()
    _pg_initialized = True


def get_db():
    """Return a DB connection compatible with the existing application."""
    if USE_POSTGRES:
        _ensure_postgres_schema()
        import psycopg2
        from psycopg2.extras import RealDictCursor
        raw = psycopg2.connect(SUPABASE_DB_URL, sslmode="require", connect_timeout=10, cursor_factory=RealDictCursor)
        return _PGConnection(raw)

    _sqlite_prepare_runtime_database()
    conn = sqlite3.connect(DB_PATH, timeout=15)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        conn.execute("PRAGMA journal_mode = WAL")
    except sqlite3.DatabaseError:
        pass
    return conn


def dict_from_row(row):
    if row is None:
        return None
    if isinstance(row, dict):
        return dict(row)
    return dict(row)
