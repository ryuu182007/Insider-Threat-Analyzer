"""Database connection layer.

- Local development: SQLite (database/insider_threat.db)
- Vercel/production: Supabase Postgres when SUPABASE_DB_URL or DATABASE_URL is set.

The application was originally written against SQLite.  The small Postgres
adapter below preserves the existing conn.execute(...), fetchone(), fetchall()
and cursor.lastrowid interface so the rest of the application does not need a
large rewrite.
"""

import os
import re
import shutil
import sqlite3

BASE_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE_DB_PATH = os.path.join(BASE_DIR, "database", "insider_threat.db")
_RUNTIME_TMP = os.path.join("/tmp", "threatsim-insider-threat.db")

SUPABASE_DB_URL = os.environ.get("SUPABASE_DB_URL") or os.environ.get("DATABASE_URL")
USE_POSTGRES = bool(SUPABASE_DB_URL)
_IS_VERCEL = os.environ.get("VERCEL") == "1"
DB_PATH = _RUNTIME_TMP if _IS_VERCEL and not USE_POSTGRES else SOURCE_DB_PATH
_initialized = False
_pg_initialized = False


